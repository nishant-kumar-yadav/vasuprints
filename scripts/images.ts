/**
 * Photo pipeline.
 *
 *   pnpm images                 rebuild src/content/images-manifest.ts from public/images
 *   pnpm images ~/Downloads/vp  import generated photos first (any of png/jpg/jpeg/webp/avif, any size),
 *                               cropped to 4:3, resized to 1600×1200 (hero 2000×1500), saved as WebP q80
 *
 * Expected layout of the import folder (same as PHOTO-PROMPTS.md):
 *   hero/home.png
 *   pages/about.png, pages/contact.png
 *   categories/<category-slug>.png
 *   products/<product-slug>/1.png … 4.png
 */
import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve('public/images');
const EXT = /\.(png|jpe?g|webp|avif)$/i;
const src = process.argv[2] ? path.resolve(process.argv[2].replace(/^~/, process.env.HOME ?? '~')) : null;

async function convert(input: string, output: string, width: number, height: number) {
  mkdirSync(path.dirname(output), { recursive: true });
  await sharp(input).rotate().resize(width, height, { fit: 'cover', position: 'attention' }).webp({ quality: 80 }).toFile(output);
  const kb = Math.round(statSync(output).size / 1024);
  console.log(`  ✓ ${path.relative(process.cwd(), output)} (${kb} KB)`);
}

const files = (dir: string) => (existsSync(dir) ? readdirSync(dir).filter((f) => EXT.test(f)).sort() : []);
const stem = (f: string) => f.replace(EXT, '');

if (src) {
  console.log(`Importing from ${src}`);
  for (const f of files(path.join(src, 'hero'))) await convert(path.join(src, 'hero', f), path.join(ROOT, 'hero', `${stem(f)}.webp`), 2000, 1500);
  for (const f of files(path.join(src, 'pages'))) await convert(path.join(src, 'pages', f), path.join(ROOT, 'pages', `${stem(f)}.webp`), 1600, 1200);
  for (const f of files(path.join(src, 'categories'))) await convert(path.join(src, 'categories', f), path.join(ROOT, 'categories', `${stem(f)}.webp`), 1600, 1200);
  const pdir = path.join(src, 'products');
  if (existsSync(pdir)) {
    for (const slug of readdirSync(pdir).filter((d) => statSync(path.join(pdir, d)).isDirectory())) {
      for (const f of files(path.join(pdir, slug))) {
        if (!/^[1-6]$/.test(stem(f))) {
          console.warn(`  ! skipped products/${slug}/${f} (name files 1–6)`);
          continue;
        }
        await convert(path.join(pdir, slug, f), path.join(ROOT, 'products', slug, `${stem(f)}.webp`), 1600, 1200);
      }
    }
  }
}

async function info(abs: string) {
  const m = await sharp(abs).metadata();
  return { src: '/' + path.relative(path.resolve('public'), abs).split(path.sep).join('/'), width: m.width ?? 1600, height: m.height ?? 1200 };
}

const manifest = { hero: null as Awaited<ReturnType<typeof info>> | null, pages: {} as Record<string, unknown>, categories: {} as Record<string, unknown>, products: {} as Record<string, unknown[]> };
const heroFile = files(path.join(ROOT, 'hero')).find((f) => stem(f) === 'home');
if (heroFile) manifest.hero = await info(path.join(ROOT, 'hero', heroFile));
for (const f of files(path.join(ROOT, 'pages'))) manifest.pages[stem(f)] = await info(path.join(ROOT, 'pages', f));
for (const f of files(path.join(ROOT, 'categories'))) manifest.categories[stem(f)] = await info(path.join(ROOT, 'categories', f));
const prodRoot = path.join(ROOT, 'products');
if (existsSync(prodRoot)) {
  for (const slug of readdirSync(prodRoot).sort()) {
    const list = files(path.join(prodRoot, slug)).filter((f) => /^[1-6]$/.test(stem(f)));
    if (list.length) manifest.products[slug] = await Promise.all(list.map((f) => info(path.join(prodRoot, slug, f))));
  }
}

const out = `// Generated by \`pnpm images\` from files in public/images. Do not edit by hand.
export interface ManifestImage {
  src: string;
  width: number;
  height: number;
}
export const imagesManifest: {
  hero: ManifestImage | null;
  pages: Record<string, ManifestImage>;
  categories: Record<string, ManifestImage>;
  products: Record<string, ManifestImage[]>;
} = ${JSON.stringify(manifest, null, 2)};
`;
writeFileSync('src/content/images-manifest.ts', out);
const n = Object.values(manifest.products).reduce((a, l) => a + l.length, 0);
console.log(`Manifest: hero ${manifest.hero ? 'yes' : 'no'}, ${Object.keys(manifest.categories).length} categories, ${Object.keys(manifest.products).length} products (${n} photos), ${Object.keys(manifest.pages).length} page images.`);
console.log('Next: pnpm build (static catalog). With CATALOG_SOURCE=mongo also run pnpm db:seed to copy photos into products that have none.');
